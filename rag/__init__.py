"""The RAG pipeline as a library, one module per stage, usable outside these experiments.

    chunking/      cuts a document into chunks, each of which records the span of the
                   document it was cut from.
    augmentation/  adds text generated by an LLM to the chunks, which is embedded with them.
    embedding      sends texts to an OpenAI-compatible endpoint and returns their vectors.
    ingestion      writes the chunks into a Chroma collection and a BM25 index.
    retrieval      searches those two stores, densely, sparsely or both at once.
    rerank         reorders the retrieved chunks with a cross-encoder, through the
                   endpoint's `/rerank` route.
    evaluation     scores a ranking against a question's evidence spans.
    judge          has an LLM score a ranking with RAGAS's context precision and recall.
    llm            holds the client every module shares, `call_llm`, and the counting
                   of tokens.

Nothing here reads a dataset, a configuration file or the environment's model
names: every function takes its inputs, models and directories explicitly.
How the experiments lay their runs out on disk is decided in `experiments/`.
"""
